# Баг
# Собираем, условно, ответы на два вопроса анкеты
# Оценка мероприятия - число, согласие на рассылку - True/False
answer_labels = {
    1: "Оценка мероприятия",
    True: "Согласие на рассылка",
}

print("Ответы:", answer_labels)
print("Количество ответов:", len(answer_labels))

# Питон считает True и 1 равными ключами словаря и вычисляет для них одинаковый хэш
# Поэтому второй ответ заменяет первый, хотя ответы относятся к разным вопросам анкеты

# Исправленная версия: используем строки как ключи словаря
answer_labels = {
    "Оценка мероприятия": 1,
    "Согласие на рассылку": True
}

print("Исправлено:", answer_labels)
print("Количество ответов:", len(answer_labels))